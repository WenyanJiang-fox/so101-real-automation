"""任务参数：走多快、抬多高、合爪用多大力。

全是调出来的经验值，每个后面写清楚「为什么是这个数」—— 这些数字比代码值钱，
换机器人的时候只有这一份要重调。

速度的单位是**控制步**：`speed_vmax()` 把「动作单位」换算成「米 / 步」，
因为 toppra 要的是米/步（见 core/follow.py 开头的说明）。
"""

from __future__ import annotations

from core.geom import CUBE_Z

POS_SCALE = 0.02     # 一个动作单位对应多少米（和 nexus 的 pd_ee_delta_pose 一致）

# ---- 速度档位（动作单位）----
SPEED = 0.015    # 巡航。**原为 0.030，2026-10-12 再砍半。** 依据是用户看录像的判断：
                 # 「真机架不住大机动」—— 真机是舵机臂，扛不住大幅度的快速摆动。这一档
                 # 和 ACCEL、follow.POS_SLEW、follow.ROT_SLEW 是一组，一起降。
                 # （0.030 那一版的原由：进场 191 帧里 184 帧平移指令超过 0.060，手臂
                 #   全程没追上参考点、方向还来回翻。）
SLOW = 0.013     # 贴近方块、贴地那几段。跟着 SPEED 一起降，保持「比巡航更轻」。
                 # 那些地方要轻，不能按巡航速度撞过去
CARRY = 0.015    # 夹着方块走。方块只是被两片爪面夹着靠摩擦跟着走，指令速度一快，
                 # 跟踪误差就来回抖，抖一次挤出去一点。实测搬运段约 21mm/s 时方块
                 # 仍以约 3mm/s 匀速后滑；压到这一档才夹得住。

# ---- 加速度档 ----
# 加/减速有多急。**速度档压下去，它得跟着压** —— 两个一起小，起步和停住才是慢慢
# 化开的，不然就是「慢慢走、到点一脚刹死」。它和 follow.POS_SLEW 说的是同一件事：
# 那边是「每步最多变多少动作量」，这边是「每步² 」，改一个记得改另一个（换算见
# acc_amax）。
ACCEL = 0.002    # 动作单位 / 控制步²  —— **2026-10-12 再砍半（0.008 → 0.004 → 0.002）**，
                 # 跟着 SPEED 一起降，见上

# ---- 抓之前把腕子转到对齐方块侧面 ----
# 单独给一步「原地转」，不塞进下探里：下探时腕子还在甩，最容易在那条路上蹭到方块。
# 转的时候位置不动，只有旋转在爬，所以斜率可以比 follow.ROT_SLEW 更小。
ALIGN_MAX_STEPS = 200    # 转不动了最多耗这么多步，别死等
ALIGN_CHUNK = 10         # 每 10 步看一次转到哪了
ALIGN_ROT_SLEW = 0.010   # 原地转的时候每步允许变多少
# **8° → 2°**（用户 2026-10-17）。8° 那一版 2026-10-17 那一趟实测停在 **7.0°**（130 步，
# 上限 200 —— 不是转不动，是一看 7.0 ≤ 8 就收手了）。那 7° 全体漏给后面造缝那一段：
# 爪子的开合轴比盒子侧面歪 7°，1 号沿切向推时有一份力气落在 ⊥缝 上，缝造不出来。
ALIGN_TOL_DEG = 2.0      # 开合轴和方块侧面差这么多度以内就算对上了

# ---- 够不够得着 ----
# 出发前先算一遍：这个点，手臂够得到吗？够不着就原地不动，别走一半卡在那儿。
# 判据不是「逆解报不报错」—— 逆解对够不着的点**不报错**，它返回「最接近的那一个」，
# 关节夹在行程上限，手停在离目标一截的地方，外人只看到「走了一半不动了」。
# 所以要反着验：拿到逆解给的关节角，正推回 TCP 位置，量一下和目标差多少。
# 差得超过这个数就算够不着。**这个数是先打的日志、后按实测两档定的**，不是拍的：
# 够得着的那几个工位残差多少、够不着的中立位残差多少，见 out 里那一轮的日志。
REACH_TOL = 0.010   # 米

# ---- 抬升 / 搬运 ----
LIFT_Z = 0.08    # 抬起和搬运高度。竖直向下的工具轴是这个 5 关节臂的极限姿势：
                 # 抬得越高，wrist_flex 越要先折满，位置只剩 4 个关节凑，手臂只能
                 # 往外鼓；下探时再从外圈横着扫回落点，路上就把旁边方块撞了。
WAYPOINT = (0.20, 0.0, 0.16)   # 中立位：每次靠近方块前先回到这里再过去

# ---- 走到点之后先停稳 ----
SETTLE_STEPS = 40   # 进场到方块上方之后，先守在这些步上把残余速度化掉，再去拍照。
                    # **不守就是「边冲边拍」**：follow 一看离目标进了 final_tol(4mm)
                    # 就说到了，那一刻手臂还在加速 —— 实测进场最后一帧平移指令
                    # 0.096 且还在涨，最后 15 帧肘关节转了 14°。相机拍到的是个还在
                    # 甩的腕子，后面转正、下探全是从一个晃着的姿态起算。
                    # 40 步的来由：残余指令约 0.09，按 POS_SLEW 0.004/步化掉要 23 步，
                    # 留一倍余量。

# ---- 合爪 / 松爪的轻重 ----
GENTLE = 0.05     # 合爪每步的指令增量。一路给满(-1.0)的话指垫是撞上去的，方块
                  # 会被推着横移、被顶得跳起来
OPEN_STEP = 0.04  # 松爪每步的指令增量，一小步一小步张，不是一步弹开
SEAT = 0.02       # 两个指垫都贴上之后，再往里挤这么多（夹爪关节角，rad）就停。
                  # 「刚贴上就停」也不行：那一瞬间法向力约等于零，抬起来会滑
STUCK_TOL = 25    # 方块和爪子都是刚体，挤到某个位置就推不动了；连着这么多步推不动
                  # 就别再耗着 —— 再合也只是把力加上去
GRIP_K = 0.05     # 守位时「被撑开多少算撑满」
GRIP_RATE = 0.12  # 守位时每步最多给多少合爪指令
GRIP_BIAS = 0.02  # 守位时恒定给的一份合爪量。**不能给 0**：那一维动作是「当前位置
                  # + 增量」，给 0 等于零刚度，爪面只是贴着方块、一点正压力都没有，
                  # 实测搬运时开口没变、方块却以约 3mm/s 匀速滑出去掉地上
GRIP_SLACK = 0.10  # 守位时允许比「合爪那一刻」再紧多少（夹爪关节角，rad）。超过就往
                   # 回松一点，不让它继续往里挤 —— 开口有个下限，方块挤不出去。
                   # 不管这一条是什么后果：那股恒定的合爪力会把方块从两指之间一点点
                   # 挤下去。实测爪关节在指令完全不变（恒 −0.02）的情况下，从 +7.65°
                   # 一路走到 −5.64° 共 0.232 rad，方块就是在这段时间掉的。
                   # 0.10 的来由：抬升那段自然回落实测 0.03~0.04 rad（+9.9° → +7.7°），
                   # 真滑出去时到了 0.232，中间空得很开，取 0.10（约 5.7°）两边都不碰
FIX_CLEAR = 0.001  # 下探时固定爪**指面**和方块侧面之间留的缝，免得刮着方块走。
                   # **从指面算**（落点里另加了指垫球伸出指垫中点的那一截，见
                   # `fixed_face_reach`）—— 只按球心算的话，这个 1mm 会被球半径吃掉大半。
OPEN_CLEAR = 0.006  # **中空件**（杯、碗）张爪时，两个指垫之间比外径多留这么多米。
                    # 为什么只对中空件：它的两个指垫只要夹住那圈壁，张开到「容得下」
                    # 就够；张满再合，活动爪要多扫一大段空行程，真机上那一下很晃。
                    # 实心件照旧张满（要给下探留余量，夹的地方也可能不是最宽处）。
                    # 6mm 是给「物体尺寸说小了、下探时蹭壁」留的余量。
AIR_TOL = 0.010    # 松爪允许高出放置高度的余量：超过它就算「还挂在半空」，不给松

# ---- 摆场（操作员把方块摆到工位上）----
PARK_FRAMES = 60        # 摆件动画的物理步数
PARK_JITTER_YAW = 0.7853981633974483       # 朝向抖动 ±45°：方块是方的，转 45° 就
                                           # 把所有可能的朝向都覆盖了。这等于把「量
                                           # 朝向」那一步放到最难的档上考
PARK_LIFT = 0.05        # 摆件时抬起的高度，免得平移时从别的方块身上刮过去
PARK_SNAP = 0.005       # 已经在工位上的方块不动，省得视频里看着像无故弹一下

# ---- 一轮跑几条 ----
N_EPISODES = 2


def speed_vmax(spd: float = SPEED) -> float:
    """把速度档（动作单位）换算成「米 / 控制步」。"""
    return float(spd) * POS_SCALE


def acc_amax(acc: float = ACCEL) -> float:
    """把加速度档（动作单位 / 步²）换算成「米 / 控制步²」，给 toppra 用。"""
    return float(acc) * POS_SCALE


def z_of_cube() -> float:
    """方块躺在地面上时中心的高度。"""
    return float(CUBE_Z)
